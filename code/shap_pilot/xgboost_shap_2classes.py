def run_binary_pipeline_for_feature_set(
    feature_set_name: str,
    X: pd.DataFrame,
    y: pd.Series,
    ids: pd.Series,
    y_rating: pd.Series,
) -> Dict[str, object]:
    print_section(f"RUN BINARY PIPELINE - {feature_set_name}")
    if y.value_counts().min() < 3:
        raise ValueError("Class thieu so qua it de chia train/validation/test an toan.")

    X_train_all, X_test, y_train_all, y_test, id_train_all, id_test, rating_train_all, rating_test = train_test_split(
        X,
        y,
        ids,
        y_rating,
        test_size=TEST_SIZE,
        random_state=RANDOM_STATE,
        stratify=y,
    )
    X_train_all = X_train_all.reset_index(drop=True)
    y_train_all = y_train_all.reset_index(drop=True)
    rating_train_all = rating_train_all.reset_index(drop=True)
    X_test = X_test.reset_index(drop=True)
    y_test = y_test.reset_index(drop=True)
    id_test = id_test.reset_index(drop=True)
    rating_test = rating_test.reset_index(drop=True)

    actual_validation_size = max(VALIDATION_SIZE, (y_train_all.nunique() + 1) / max(len(y_train_all), 1))
    X_fit, X_val, y_fit, y_val = train_test_split(
        X_train_all,
        y_train_all,
        test_size=actual_validation_size,
        random_state=RANDOM_STATE,
        stratify=y_train_all,
    )
    X_fit = X_fit.reset_index(drop=True)
    X_val = X_val.reset_index(drop=True)
    y_fit = y_fit.reset_index(drop=True)
    y_val = y_val.reset_index(drop=True)

    tuning_df = run_tuning_grid_for_feature_set(feature_set_name, X_fit, y_fit, X_val, y_val)
    best_row = tuning_df.iloc[0]
    model, oversample_status, resampled_counts = fit_xgb_binary(
        X_fit,
        y_fit,
        X_val,
        y_val,
        str(best_row["oversample_strategy"]),
        float(best_row["oversample_ratio"]),
        float(best_row["non_positive_weight"]),
        RANDOM_STATE + 900,
    )
    print(f"  Best {feature_set_name}: {best_row['oversample_strategy']} | ratio={best_row['oversample_ratio']} | w0={best_row['non_positive_weight']}")
    print(f"  Oversample status: {oversample_status} | Resampled: {resampled_counts}")

    val_proba = get_positive_proba(model, X_val)
    threshold_df, threshold_best, threshold_recall_best = search_binary_thresholds(y_val, val_proba)
    threshold_df.insert(0, "feature_set", feature_set_name)
    save_csv(threshold_df, f"threshold_search_{feature_set_name}.csv")
    best_threshold = float(threshold_best["threshold"])

    test_proba = get_positive_proba(model, X_test)
    y_pred = predict_non_positive_threshold(test_proba, best_threshold)
    metrics_df, metrics = model_metrics_table(y_test, y_pred, test_proba)
    metrics["feature_set"] = feature_set_name
    metrics["best_threshold"] = best_threshold
    metrics["best_recall_threshold"] = float(threshold_recall_best["threshold"])
    metrics["oversample_strategy"] = str(best_row["oversample_strategy"])
    metrics["oversample_ratio"] = float(best_row["oversample_ratio"])
    metrics["non_positive_weight"] = float(best_row["non_positive_weight"])
    metrics_wide_df = pd.DataFrame([metrics])
    save_csv(metrics_wide_df, f"metrics_{feature_set_name}.csv")

    predictions_df = make_predictions_df(id_test, rating_test, y_test, y_pred, test_proba, best_threshold)
    predictions_df.insert(0, "feature_set", feature_set_name)
    save_csv(predictions_df, f"predictions_{feature_set_name}.csv")

    cv_df = run_cross_validation_feature_set(feature_set_name, X, y, best_row)

    try:
        shap_non_positive_df, shap_note = run_prefixed_shap_analysis(feature_set_name, model, X_test)
    except Exception as exc:
        print(f"  [WARN] SHAP loi voi {feature_set_name}: {exc}. Van giu metrics/predictions.")
        shap_non_positive_df = empty_shap_importance(feature_set_name)
        shap_note = f"SHAP failed for {feature_set_name}: {exc}"

    return {
        "feature_set": feature_set_name,
        "model": model,
        "best_row": best_row,
        "threshold_best": threshold_best,
        "metrics": metrics,
        "metrics_df": metrics_wide_df,
        "predictions_df": predictions_df,
        "cv_df": cv_df,
        "shap_non_positive_df": shap_non_positive_df,
        "shap_note": shap_note,
    }


def topic_slug_from_feature(feature: str) -> Optional[str]:
    for slug in TOPIC_SLUGS.values():
        if feature.endswith(f"_{slug}") or feature == slug:
            return slug
    return None


def aggregate_topic_shap(shap_df: pd.DataFrame) -> pd.DataFrame:
    rows = []
    if shap_df.empty or "feature" not in shap_df.columns:
        for topic_id in TOPIC_IDS:
            rows.append({"topic": TOPIC_SLUGS[topic_id], "mean_abs_shap": np.nan})
        return pd.DataFrame(rows)

    tmp = shap_df.copy()
    tmp["topic"] = tmp["feature"].apply(topic_slug_from_feature)
    tmp = tmp.dropna(subset=["topic"])
    grouped = tmp.groupby("topic")["mean_abs_shap"].sum()
    for topic_id in TOPIC_IDS:
        slug = TOPIC_SLUGS[topic_id]
        rows.append({"topic": slug, "mean_abs_shap": float(grouped.get(slug, np.nan))})
    return pd.DataFrame(rows)


def compare_shap_vs_topic_popularity(
    shap_df: pd.DataFrame,
    topic_popularity_df: pd.DataFrame,
    model_name: str,
) -> Tuple[pd.DataFrame, Dict[str, object]]:
    shap_topic_df = aggregate_topic_shap(shap_df)
    merged = topic_popularity_df.merge(shap_topic_df, on="topic", how="left")
    merged["rank_popularity"] = merged["clause_count"].rank(ascending=False, method="min").astype(int)
    merged["rank_shap"] = merged["mean_abs_shap"].rank(ascending=False, method="min")
    merged["rank_diff"] = merged["rank_popularity"] - merged["rank_shap"]
    merged.insert(0, "model_name", model_name)

    valid = merged[["clause_count", "mean_abs_shap"]].dropna()
    if len(valid) >= 2 and valid["mean_abs_shap"].std() > 0 and valid["clause_count"].std() > 0:
        spearman_corr = float(valid["clause_count"].corr(valid["mean_abs_shap"], method="spearman"))
        pearson_corr = float(valid["clause_count"].corr(valid["mean_abs_shap"], method="pearson"))
    else:
        spearman_corr = np.nan
        pearson_corr = np.nan

    if pd.notna(spearman_corr) and spearman_corr > 0.7:
        note = "SHAP ranking may be strongly aligned with topic popularity. Interpret topic importance carefully."
    else:
        note = "SHAP ranking is not merely reflecting topic popularity."

    save_csv(merged, f"shap_vs_popularity_{model_name}.csv")

    fig, ax = plt.subplots(figsize=(7, 5))
    plot_data = merged.dropna(subset=["mean_abs_shap"]).copy()
    if plot_data.empty:
        ax.text(0.5, 0.5, "No SHAP values available", ha="center", va="center")
        ax.set_axis_off()
    else:
        sns.scatterplot(data=plot_data, x="clause_count", y="mean_abs_shap", hue="topic_name", s=80, ax=ax)
        for _, row in plot_data.iterrows():
            ax.text(row["clause_count"], row["mean_abs_shap"], str(row["topic_id"]), fontsize=9)
        ax.set_xlabel("Clause count")
        ax.set_ylabel("Aggregated mean |SHAP|")
        ax.grid(alpha=0.25)
    ax.set_title(f"SHAP vs topic popularity - {model_name}")
    plt.tight_layout()
    savefig(f"shap_vs_popularity_scatter_{model_name}.png")

    corr_row = {
        "model_name": model_name,
        "spearman_clause_count_vs_shap": spearman_corr,
        "pearson_clause_count_vs_shap": pearson_corr,
        "interpretation": note,
    }
    print(f"  {model_name}: Spearman popularity vs SHAP = {spearman_corr:.4f} | {note}")
    return merged, corr_row


def build_shap_rank_stability(
    topic_popularity_df: pd.DataFrame,
    comparison_tables: Dict[str, pd.DataFrame],
) -> pd.DataFrame:
    base = topic_popularity_df[["topic", "topic_name", "rank_popularity"]].copy()
    base = base.rename(columns={"rank_popularity": "popularity_rank"})
    output = base.copy()
    for model_name, table in comparison_tables.items():
        cols = table[["topic", "rank_shap", "mean_abs_shap"]].copy()
        cols = cols.rename(
            columns={
                "rank_shap": f"shap_rank_{model_name.replace('explain_', '').replace('predict_', '')}",
                "mean_abs_shap": f"mean_abs_shap_{model_name.replace('explain_', '').replace('predict_', '')}",
            }
        )
        output = output.merge(cols, on="topic", how="left")

    rank_wo = "shap_rank_weighted_only"
    rank_wr = "shap_rank_weighted_ratio"
    rank_full = "shap_rank_full"
    notes = []
    for _, row in output.iterrows():
        note_parts = []
        if rank_wo in output.columns and rank_wr in output.columns:
            if pd.notna(row[rank_wo]) and pd.notna(row[rank_wr]) and abs(row[rank_wo] - row[rank_wr]) <= 1:
                note_parts.append("stable")
            else:
                note_parts.append("weighted_only_vs_ratio_changed")
        if rank_full in output.columns and rank_wo in output.columns:
            if pd.notna(row[rank_full]) and pd.notna(row[rank_wo]) and abs(row[rank_full] - row[rank_wo]) > 2:
                note_parts.append("full model may be affected by expanded features")
        notes.append("; ".join(note_parts) if note_parts else "stable")
    output["rank_stable_note"] = notes
    save_csv(output, "shap_rank_stability_comparison.csv")

    heatmap_cols = [column for column in output.columns if column.startswith("shap_rank_")]
    if heatmap_cols:
        heatmap_df = output.set_index("topic_name")[heatmap_cols]
        fig, ax = plt.subplots(figsize=(8, 4.8))
        sns.heatmap(heatmap_df, annot=True, fmt=".0f", cmap="YlGnBu_r", ax=ax)
        ax.set_title("SHAP rank stability across feature sets")
        ax.set_xlabel("Model")
        ax.set_ylabel("Topic")
        plt.tight_layout()
        savefig("shap_rank_stability_heatmap.png")
    return output


def build_model_role_recommendation(model_comparison_df: pd.DataFrame, corr_summary_df: pd.DataFrame) -> str:
    sorted_models = model_comparison_df.sort_values(
        ["macro_f1", "balanced_accuracy", "recall_non_positive", "precision_non_positive"],
        ascending=[False, False, False, False],
    )
    best_prediction = sorted_models.iloc[0]["feature_set"]
    explanation_model = "explain_weighted_only"
    full_corr_row = corr_summary_df[corr_summary_df["model_name"] == "predict_full"]
    full_corr = np.nan if full_corr_row.empty else float(full_corr_row.iloc[0]["spearman_clause_count_vs_shap"])
    weighted_row = model_comparison_df[model_comparison_df["feature_set"] == explanation_model].iloc[0]
    best_row = sorted_models.iloc[0]
    macro_gap = float(best_row["macro_f1"] - weighted_row["macro_f1"])
    ba_gap = float(best_row["balanced_accuracy"] - weighted_row["balanced_accuracy"])

    if best_prediction == "predict_full":
        if pd.notna(full_corr) and full_corr > 0.7:
            recommendation = (
                "Predict_full dat hieu qua du doan tot nhat, nhung SHAP cua no co the bi anh huong "
                "boi count/sum va do pho bien topic. Vi vay, nghien cuu dung predict_full cho du doan "
                "va dung explain_weighted_only de dien giai 5 nhom yeu to chinh."
            )
        else:
            recommendation = (
                "Predict_full dat hieu qua du doan tot nhat. Tuy nhien, de bao cao 5 topic, "
                "van nen dung explain_weighted_only lam mo hinh giai thich chinh vi no khong dung "
                "topic_count/topic_sum."
            )
    elif macro_gap <= 0.03 and ba_gap <= 0.03:
        recommendation = (
            "Explain_weighted_only co hieu qua khong kem dang ke va don gian hon, nen co the dung "
            "lam mo hinh chinh de vua du doan vua giai thich."
        )
    else:
        recommendation = (
            f"{best_prediction} la mo hinh du doan tot nhat, con explain_weighted_only la mo hinh "
            "giai thich chinh de han che popularity/frequency bias."
        )

    text = f"""MODEL ROLE RECOMMENDATION
{SEP}
Best prediction model: {best_prediction}
Best explanation model: {explanation_model}
Macro F1 gap best - explain_weighted_only: {macro_gap:.4f}
Balanced Accuracy gap best - explain_weighted_only: {ba_gap:.4f}
Spearman popularity correlation for predict_full: {full_corr:.4f}

Recommendation:
{recommendation}
"""
    save_text(text, "model_role_recommendation.txt")
    return text


