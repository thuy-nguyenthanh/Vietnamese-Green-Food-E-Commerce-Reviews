def shap_top_features_for_hybrid_predictions(
    model: XGBClassifier,
    X_test: pd.DataFrame,
    pred_hybrid_best: np.ndarray,
) -> pd.DataFrame:
    explainer = shap.TreeExplainer(model)
    raw_shap = explainer.shap_values(X_test)
    shap_positive, _ = normalize_binary_shap(raw_shap)
    shap_non_positive = -shap_positive
    feature_names = list(X_test.columns)
    top_idx = np.argmax(np.abs(shap_non_positive), axis=1)
    top_features = [feature_names[int(idx)] for idx in top_idx]
    top_values = [float(shap_non_positive[row_idx, int(col_idx)]) for row_idx, col_idx in enumerate(top_idx)]
    rows = []
    for idx, pred in enumerate(pred_hybrid_best):
        if int(pred) == 0:
            explanation = f"Yeu to anh huong manh nhat den du doan non_positive: {top_features[idx]}"
            rows.append(
                {
                    "top_shap_feature": top_features[idx],
                    "top_shap_value": top_values[idx],
                    "shap_explanation_short": explanation,
                }
            )
        else:
            rows.append(
                {
                    "top_shap_feature": "",
                    "top_shap_value": np.nan,
                    "shap_explanation_short": "",
                }
            )
    shap_top_df = pd.DataFrame(rows)
    save_csv(shap_top_df[shap_top_df["top_shap_feature"] != ""], "shap_top_features_for_hybrid_non_positive.csv")
    return shap_top_df


def run_cross_validation_hybrid(
    X: pd.DataFrame,
    y: pd.Series,
    y_rating: pd.Series,
    best_binary_row: pd.Series,
) -> Optional[pd.DataFrame]:
    print_section("BUOC 8 - CROSS-VALIDATION HYBRID")
    if not RUN_CV_HYBRID:
        save_text(
            "Cross-validation hybrid was skipped because RUN_CV_HYBRID=False",
            "cross_validation_hybrid_skipped.txt",
        )
        return None

    min_class_count = int(y.value_counts().min())
    n_splits = min(N_SPLITS_CV, min_class_count)
    if n_splits < 2:
        save_text("Cross-validation hybrid skipped: not enough minority samples.", "cross_validation_hybrid_skipped.txt")
        return None

    skf = StratifiedKFold(n_splits=n_splits, shuffle=True, random_state=RANDOM_STATE)
    rows = []
    for fold, (outer_train_idx, outer_val_idx) in enumerate(skf.split(X, y), 1):
        inner_train_idx, inner_val_idx = train_test_split(
            outer_train_idx,
            test_size=VALIDATION_SIZE,
            random_state=RANDOM_STATE + fold,
            stratify=y.iloc[outer_train_idx],
        )
        X_inner_fit = X.iloc[inner_train_idx].reset_index(drop=True)
        y_inner_fit = y.iloc[inner_train_idx].reset_index(drop=True)
        rating_inner_fit = y_rating.iloc[inner_train_idx].reset_index(drop=True)
        X_inner_val = X.iloc[inner_val_idx].reset_index(drop=True)
        y_inner_val = y.iloc[inner_val_idx].reset_index(drop=True)
        rating_inner_val = y_rating.iloc[inner_val_idx].reset_index(drop=True)
        X_outer_val = X.iloc[outer_val_idx].reset_index(drop=True)
        y_outer_val = y.iloc[outer_val_idx].reset_index(drop=True)

        cls_model, _, _ = fit_xgb_binary(
            X_inner_fit,
            y_inner_fit,
            X_inner_val,
            y_inner_val,
            str(best_binary_row["oversample_strategy"]),
            float(best_binary_row["oversample_ratio"]),
            float(best_binary_row["non_positive_weight"]),
            RANDOM_STATE + 300 + fold,
        )
        cls_inner_risk = 1.0 - get_positive_proba(cls_model, X_inner_val)
        cls_outer_risk = 1.0 - get_positive_proba(cls_model, X_outer_val)

        reg_inner_risk = None
        reg_outer_risk = None
        try:
            reg_model = fit_xgb_regressor(
                X_inner_fit,
                rating_inner_fit,
                X_inner_val,
                rating_inner_val,
                RANDOM_STATE + 400 + fold,
            )
            _, reg_inner_clipped, _ = predict_rating_outputs(reg_model, X_inner_val)
            _, reg_outer_clipped, _ = predict_rating_outputs(reg_model, X_outer_val)
            reg_inner_risk = regression_risk_from_rating(reg_inner_clipped)
            reg_outer_risk = regression_risk_from_rating(reg_outer_clipped)
        except Exception as exc:
            print(f"  [WARN] Fold {fold}: regression loi, chi dung binary/sentiment risk. {exc}")

        _, sent_inner_risk = get_sentiment_mean_and_risk(X_inner_val, f"inner_val_fold_{fold}", warn=False)
        _, sent_outer_risk = get_sentiment_mean_and_risk(X_outer_val, f"outer_val_fold_{fold}", warn=False)

        fold_grid_df, fold_best = search_hybrid_grid(
            y_inner_val,
            cls_inner_risk,
            reg_inner_risk,
            sent_inner_risk,
            save_outputs=False,
        )
        outer_risk = get_hybrid_risk(fold_best, cls_outer_risk, reg_outer_risk, sent_outer_risk)
        outer_pred = np.where(outer_risk >= float(fold_best["tau"]), 0, 1)
        row = hybrid_metric_row(y_outer_val, outer_pred, outer_risk, float(fold_best["tau"]))
        row.update(
            {
                "fold": fold,
                "best_method": fold_best["method"],
                "best_weights": fold_best["best_weights"],
                "best_tau": float(fold_best["tau"]),
                "inner_grid_size": len(fold_grid_df),
            }
        )
        rows.append(row)
        print(
            f"  Fold {fold}: {fold_best['method']} | tau={float(fold_best['tau']):.2f} | "
            f"MacroF1={row['macro_f1']:.4f} | BA={row['balanced_accuracy']:.4f} | "
            f"R0={row['recall_non_positive']:.4f}"
        )

    cv_df = pd.DataFrame(rows)
    ordered = [
        "fold",
        "best_method",
        "best_weights",
        "best_tau",
        "macro_f1",
        "balanced_accuracy",
        "precision_non_positive",
        "recall_non_positive",
        "f1_non_positive",
        "roc_auc",
        "TP_non_positive",
        "FN_non_positive",
        "FP_non_positive",
        "TN_non_positive",
        "inner_grid_size",
    ]
    cv_df = cv_df[ordered]
    save_csv(cv_df, "cross_validation_hybrid.csv")
    return cv_df


