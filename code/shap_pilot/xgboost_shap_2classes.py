def evaluate_hybrid_methods_on_test(
    y_test: pd.Series,
    classification_risk: np.ndarray,
    regression_risk: Optional[np.ndarray],
    sentiment_risk: Optional[np.ndarray],
    grid_df: pd.DataFrame,
    best_row: pd.Series,
) -> Tuple[pd.DataFrame, pd.DataFrame, Dict[str, float], np.ndarray, np.ndarray, pd.DataFrame]:
    method_order = [
        "Binary only",
        "Regression risk only",
        "Sentiment risk only",
        "Binary + Regression",
        "Binary + Sentiment",
        "Binary + Regression + Sentiment",
    ]
    by_method_df = best_hybrid_rows_by_method(grid_df)
    rows = []
    for method in method_order:
        matches = by_method_df[by_method_df["method"] == method]
        if matches.empty:
            continue
        config = matches.iloc[0]
        try:
            risk = get_hybrid_risk(config, classification_risk, regression_risk, sentiment_risk)
        except ValueError:
            continue
        tau = float(config["tau"])
        pred = np.where(risk >= tau, 0, 1)
        row = hybrid_metric_row(y_test, pred, risk, tau)
        row.update(
            {
                "method": method,
                "w_cls": float(config["w_cls"]),
                "w_reg": float(config["w_reg"]),
                "w_sent": float(config["w_sent"]),
                "best_weights": config["best_weights"],
            }
        )
        rows.append(row)

    comparison_df = pd.DataFrame(rows)
    comparison_df["method_order"] = comparison_df["method"].map({name: idx for idx, name in enumerate(method_order)})
    comparison_df = comparison_df.sort_values("method_order").drop(columns=["method_order"]).reset_index(drop=True)

    best_risk = get_hybrid_risk(best_row, classification_risk, regression_risk, sentiment_risk)
    best_tau = float(best_row["tau"])
    best_pred = np.where(best_risk >= best_tau, 0, 1)
    best_metrics = hybrid_metric_row(y_test, best_pred, best_risk, best_tau)
    best_metrics.update(
        {
            "method": best_row["method"],
            "w_cls": float(best_row["w_cls"]),
            "w_reg": float(best_row["w_reg"]),
            "w_sent": float(best_row["w_sent"]),
            "best_weights": best_row["best_weights"],
        }
    )
    metrics_df = pd.DataFrame([{"metric": key, "value": value} for key, value in best_metrics.items()])
    return comparison_df, metrics_df, best_metrics, best_pred, best_risk, by_method_df


def get_method_prediction(
    method_name: str,
    by_method_df: pd.DataFrame,
    classification_risk: np.ndarray,
    regression_risk: Optional[np.ndarray],
    sentiment_risk: Optional[np.ndarray],
) -> np.ndarray:
    matches = by_method_df[by_method_df["method"] == method_name]
    if matches.empty:
        return np.full(len(classification_risk), np.nan)
    config = matches.iloc[0]
    try:
        risk = get_hybrid_risk(config, classification_risk, regression_risk, sentiment_risk)
    except ValueError:
        return np.full(len(classification_risk), np.nan)
    return np.where(risk >= float(config["tau"]), 0, 1)


