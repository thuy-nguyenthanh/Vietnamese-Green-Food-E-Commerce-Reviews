def hybrid_weights_to_string(row: pd.Series) -> str:
    return (
        f"w_cls={float(row.get('w_cls', 0.0)):.2f}, "
        f"w_reg={float(row.get('w_reg', 0.0)):.2f}, "
        f"w_sent={float(row.get('w_sent', 0.0)):.2f}"
    )


def make_hybrid_weight_configs(has_regression: bool, has_sentiment: bool) -> List[Dict[str, float]]:
    configs: List[Dict[str, float]] = [
        {"method": "Binary only", "w_cls": 1.0, "w_reg": 0.0, "w_sent": 0.0}
    ]
    if has_regression:
        configs.append({"method": "Regression risk only", "w_cls": 0.0, "w_reg": 1.0, "w_sent": 0.0})
        for w_cls in HYBRID_WEIGHT_GRID:
            configs.append(
                {
                    "method": "Binary + Regression",
                    "w_cls": float(w_cls),
                    "w_reg": float(round(1.0 - w_cls, 2)),
                    "w_sent": 0.0,
                }
            )
    if has_sentiment:
        configs.append({"method": "Sentiment risk only", "w_cls": 0.0, "w_reg": 0.0, "w_sent": 1.0})
        for w_cls in HYBRID_WEIGHT_GRID:
            configs.append(
                {
                    "method": "Binary + Sentiment",
                    "w_cls": float(w_cls),
                    "w_reg": 0.0,
                    "w_sent": float(round(1.0 - w_cls, 2)),
                }
            )
    if has_regression and has_sentiment:
        for w_cls in HYBRID_WEIGHT_GRID:
            for w_reg in HYBRID_WEIGHT_GRID:
                w_sent = round(1.0 - float(w_cls) - float(w_reg), 2)
                if -1e-9 <= w_sent <= 1.0 + 1e-9:
                    configs.append(
                        {
                            "method": "Binary + Regression + Sentiment",
                            "w_cls": float(w_cls),
                            "w_reg": float(w_reg),
                            "w_sent": float(max(0.0, min(1.0, w_sent))),
                        }
                    )
    unique = []
    seen = set()
    for config in configs:
        key = (config["method"], config["w_cls"], config["w_reg"], config["w_sent"])
        if key not in seen:
            seen.add(key)
            unique.append(config)
    return unique


def get_hybrid_risk(
    config: pd.Series,
    classification_risk: np.ndarray,
    regression_risk: Optional[np.ndarray],
    sentiment_risk: Optional[np.ndarray],
) -> np.ndarray:
    w_cls = float(config.get("w_cls", 0.0))
    w_reg = float(config.get("w_reg", 0.0))
    w_sent = float(config.get("w_sent", 0.0))
    risk = w_cls * np.asarray(classification_risk, dtype=float)
    if w_reg > 0:
        if regression_risk is None:
            raise ValueError("Config can regression_risk nhung regression_risk=None.")
        risk = risk + w_reg * np.asarray(regression_risk, dtype=float)
    if w_sent > 0:
        if sentiment_risk is None:
            raise ValueError("Config can sentiment_risk nhung sentiment_risk=None.")
        risk = risk + w_sent * np.asarray(sentiment_risk, dtype=float)
    return np.clip(risk, 0.0, 1.0)


def hybrid_metric_row(
    y_true: pd.Series,
    y_pred: np.ndarray,
    risk_non_positive: np.ndarray,
    tau: Optional[float] = None,
) -> Dict[str, float]:
    cm = confusion_matrix(y_true, y_pred, labels=[0, 1])
    cm00, cm01, cm10, cm11 = cm.ravel()
    row: Dict[str, float] = {
        "macro_f1": f1_score(y_true, y_pred, average="macro", zero_division=0),
        "balanced_accuracy": balanced_accuracy_score(y_true, y_pred),
        "precision_non_positive": precision_score(y_true, y_pred, pos_label=0, zero_division=0),
        "recall_non_positive": recall_score(y_true, y_pred, pos_label=0, zero_division=0),
        "f1_non_positive": f1_score(y_true, y_pred, pos_label=0, zero_division=0),
        "accuracy": accuracy_score(y_true, y_pred),
        "TP_non_positive": int(cm00),
        "FN_non_positive": int(cm01),
        "FP_non_positive": int(cm10),
        "TN_non_positive": int(cm11),
        "TN": int(cm00),
        "FP": int(cm01),
        "FN": int(cm10),
        "TP": int(cm11),
    }
    if tau is not None:
        row["tau"] = float(tau)
    if len(np.unique(y_true)) == 2:
        try:
            row["roc_auc"] = roc_auc_score((np.asarray(y_true) == 0).astype(int), risk_non_positive)
        except Exception:
            row["roc_auc"] = np.nan
    else:
        row["roc_auc"] = np.nan
    return row


def search_hybrid_grid(
    y_true: pd.Series,
    classification_risk: np.ndarray,
    regression_risk: Optional[np.ndarray],
    sentiment_risk: Optional[np.ndarray],
    save_outputs: bool = True,
) -> Tuple[pd.DataFrame, pd.Series]:
    has_regression = regression_risk is not None
    has_sentiment = sentiment_risk is not None
    configs = make_hybrid_weight_configs(has_regression, has_sentiment)
    rows = []
    for config in configs:
        config_series = pd.Series(config)
        try:
            risk = get_hybrid_risk(config_series, classification_risk, regression_risk, sentiment_risk)
        except ValueError:
            continue
        for tau in HYBRID_TAU_GRID:
            y_pred = np.where(risk >= float(tau), 0, 1)
            row = hybrid_metric_row(y_true, y_pred, risk, float(tau))
            row.update(config)
            row["best_weights"] = hybrid_weights_to_string(pd.Series(config))
            rows.append(row)

    if not rows:
        raise ValueError("Khong co cau hinh hybrid hop le de grid search.")

    grid_df = pd.DataFrame(rows)
    grid_df = grid_df.sort_values(
        ["macro_f1", "balanced_accuracy", "recall_non_positive", "precision_non_positive"],
        ascending=[False, False, False, False],
    ).reset_index(drop=True)
    grid_df.insert(0, "rank", np.arange(1, len(grid_df) + 1))
    best_row = grid_df.iloc[0]
    if save_outputs:
        save_csv(grid_df, "hybrid_grid_search_results.csv")
    return grid_df, best_row


