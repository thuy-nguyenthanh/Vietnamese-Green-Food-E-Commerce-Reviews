def predict_rating_outputs(model: XGBRegressor, X: pd.DataFrame) -> Tuple[np.ndarray, np.ndarray, np.ndarray]:
    pred_rating_raw = np.asarray(model.predict(X), dtype=float)
    pred_rating_clipped = np.clip(pred_rating_raw, 1.0, 5.0)
    pred_rating_rounded = np.rint(pred_rating_clipped).astype(int)
    pred_rating_rounded = np.clip(pred_rating_rounded, 1, 5)
    return pred_rating_raw, pred_rating_clipped, pred_rating_rounded


def regression_risk_from_rating(pred_rating_clipped: np.ndarray) -> np.ndarray:
    return np.clip((5.0 - np.asarray(pred_rating_clipped, dtype=float)) / 4.0, 0.0, 1.0)


def get_sentiment_mean_and_risk(
    X: pd.DataFrame,
    context: str,
    warn: bool = True,
) -> Tuple[Optional[np.ndarray], Optional[np.ndarray]]:
    if "sentiment_mean" not in X.columns:
        if warn:
            print(f"  [WARN] Khong co sentiment_mean trong X_{context}. Bo qua nhanh sentiment risk.")
        return None, None
    sentiment_mean = X["sentiment_mean"].to_numpy(dtype=float)
    sentiment_risk = np.clip((1.0 - sentiment_mean) / 2.0, 0.0, 1.0)
    return sentiment_mean, sentiment_risk


def regression_metrics_table(
    y_rating_true: pd.Series,
    pred_rating_clipped: np.ndarray,
    pred_rating_rounded: np.ndarray,
) -> Tuple[pd.DataFrame, Dict[str, float]]:
    true_values = np.asarray(y_rating_true, dtype=float)
    true_rounded = np.asarray(y_rating_true, dtype=int)
    metrics = {
        "mae": mean_absolute_error(true_values, pred_rating_clipped),
        "rmse": float(np.sqrt(mean_squared_error(true_values, pred_rating_clipped))),
        "r2": r2_score(true_values, pred_rating_clipped),
        "exact_accuracy_rounded": accuracy_score(true_rounded, pred_rating_rounded),
        "within_1_star_accuracy": float(np.mean(np.abs(pred_rating_rounded - true_rounded) <= 1)),
    }
    try:
        metrics["quadratic_weighted_kappa"] = cohen_kappa_score(
            true_rounded,
            pred_rating_rounded,
            weights="quadratic",
        )
    except Exception:
        metrics["quadratic_weighted_kappa"] = np.nan
    metrics_df = pd.DataFrame([{"metric": key, "value": value} for key, value in metrics.items()])
    return metrics_df, metrics


