def run_cross_validation_optimized(
    X: pd.DataFrame,
    y: pd.Series,
    best_row: pd.Series,
) -> pd.DataFrame:
    print_section("BUOC 6 - CROSS-VALIDATION KHONG RO RI")
    min_class_count = int(y.value_counts().min())
    n_splits = min(N_SPLITS_CV, min_class_count)
    if n_splits < 2:
        raise ValueError("Khong du mau class thieu so de chay cross-validation.")

    skf = StratifiedKFold(n_splits=n_splits, shuffle=True, random_state=RANDOM_STATE)
    rows = []
    for fold, (train_idx, outer_val_idx) in enumerate(skf.split(X, y), 1):
        X_fold_train = X.iloc[train_idx].reset_index(drop=True)
        y_fold_train = y.iloc[train_idx].reset_index(drop=True)
        X_outer_val = X.iloc[outer_val_idx].reset_index(drop=True)
        y_outer_val = y.iloc[outer_val_idx].reset_index(drop=True)

        X_fold_fit, X_fold_threshold, y_fold_fit, y_fold_threshold = safe_train_validation_split(
            X_fold_train,
            y_fold_train,
            VALIDATION_SIZE,
            RANDOM_STATE + fold,
        )
        model, oversample_status, _ = fit_xgb_binary(
            X_fold_fit,
            y_fold_fit,
            X_fold_threshold,
            y_fold_threshold,
            str(best_row["oversample_strategy"]),
            float(best_row["oversample_ratio"]),
            float(best_row["non_positive_weight"]),
            RANDOM_STATE + 100 + fold,
        )
        threshold_proba = get_positive_proba(model, X_fold_threshold)
        _, fold_best_threshold, _ = search_binary_thresholds(y_fold_threshold, threshold_proba)
        best_threshold = float(fold_best_threshold["threshold"])

        outer_proba = get_positive_proba(model, X_outer_val)
        outer_pred = predict_non_positive_threshold(outer_proba, best_threshold)
        row = metric_row(y_outer_val, outer_pred, best_threshold, outer_proba)
        row.update(
            {
                "fold": fold,
                "best_threshold": best_threshold,
                "oversample_status": oversample_status,
            }
        )
        rows.append(row)
        print(
            f"  Fold {fold}: threshold={best_threshold:.2f} | "
            f"MacroF1={row['macro_f1']:.4f} | BA={row['balanced_accuracy']:.4f} | "
            f"R0={row['recall_non_positive']:.4f} | AUC={row.get('auc', np.nan):.4f}"
        )

    cv_df = pd.DataFrame(rows)
    ordered = [
        "fold",
        "best_threshold",
        "macro_f1",
        "balanced_accuracy",
        "precision_non_positive",
        "recall_non_positive",
        "f1_non_positive",
        "auc",
        "TN",
        "FP",
        "FN",
        "TP",
        "oversample_status",
    ]
    cv_df = cv_df[ordered]
    save_csv(cv_df, "cross_validation_binary_optimized.csv")
    return cv_df


