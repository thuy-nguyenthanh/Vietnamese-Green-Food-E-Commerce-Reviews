def first_numeric(series: pd.Series) -> float:
    values = pd.to_numeric(series, errors="coerce").dropna()
    if values.empty:
        return np.nan
    return float(values.iloc[0])


def rating_to_binary_group(rating: object) -> Optional[int]:
    try:
        value = int(rating)
    except Exception:
        return None
    if value in [4, 5]:
        return 1
    if value in [1, 2, 3]:
        return 0
    return None


def normalize_final_label_to_score(label: object) -> Optional[float]:
    if pd.isna(label):
        return None
    normalized = str(label).strip().upper()
    mapping = {
        "POS": 1.0,
        "POSITIVE": 1.0,
        "TICH_CUC": 1.0,
        "TICH CUC": 1.0,
        "NEG": -1.0,
        "NEGATIVE": -1.0,
        "TIEU_CUC": -1.0,
        "TIEU CUC": -1.0,
        "NEU": 0.0,
        "NEUTRAL": 0.0,
        "TRUNG_TINH": 0.0,
        "TRUNG TINH": 0.0,
    }
    return mapping.get(normalized)


def choose_and_read_excel(input_file: str, sheet_name=None) -> Tuple[pd.DataFrame, str, List[str]]:
    excel_file = pd.ExcelFile(input_file)
    available = excel_file.sheet_names
    preferred = None if sheet_name in [None, "", "AUTO", "auto"] else sheet_name
    if preferred and preferred in available:
        selected = preferred
    elif "confidence_ge_0_8" in available:
        selected = "confidence_ge_0_8"
    elif "predictions_cleaned_v2" in available:
        selected = "predictions_cleaned_v2"
    else:
        selected = available[0]
    df = pd.read_excel(input_file, sheet_name=selected, dtype={"id": str})
    df.columns = [str(column).strip() for column in df.columns]
    return df, selected, available


def print_distribution(series: pd.Series, title: str, label_map: Optional[Dict[int, str]] = None) -> pd.DataFrame:
    dist = series.value_counts().sort_index()
    total = int(dist.sum())
    rows = []
    print(f"\n  {title}:")
    for key, count in dist.items():
        label = label_map.get(int(key), key) if label_map else key
        percent = (count / total * 100.0) if total else 0.0
        print(f"    {label}: {int(count):,} ({percent:.2f}%)")
        rows.append({"class": int(key), "label": label, "count": int(count), "percent": percent})
    return pd.DataFrame(rows)


def warn_if_imbalanced(y: pd.Series) -> None:
    dist = y.value_counts()
    if dist.empty:
        return
    ratio = float("inf") if dist.min() == 0 else dist.max() / dist.min()
    print(f"\n  Ty le mat can bang max/min: {ratio:.1f}x")
    if ratio >= 10:
        print("  [WARN] Du lieu mat can bang nang. Khong dung Accuracy de chon model.")
        print("  Uu tien Macro F1, Balanced Accuracy, Recall[non_positive].")


def safe_train_validation_split(
    X: pd.DataFrame,
    y: pd.Series,
    test_size: float,
    random_state: int,
) -> Tuple[pd.DataFrame, pd.DataFrame, pd.Series, pd.Series]:
    n_classes = y.nunique()
    minimum_test_fraction = (n_classes + 1) / max(len(y), 1)
    actual_test_size = max(test_size, minimum_test_fraction)
    counts = y.value_counts()
    if counts.min() < 2:
        raise ValueError("Khong du mau moi class de tach validation co stratify.")
    return train_test_split(
        X,
        y,
        test_size=actual_test_size,
        random_state=random_state,
        stratify=y,
    )


