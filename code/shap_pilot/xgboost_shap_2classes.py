def build_sampling_strategy(y: pd.Series, ratio: float) -> Dict[int, int]:
    counts = Counter(y)
    if 0 not in counts or 1 not in counts:
        return {}
    target_count = int(round(counts[1] * ratio))
    target_count = max(target_count, counts[0])
    if target_count <= counts[0]:
        return {}
    return {0: target_count}


def apply_oversampling(
    X: pd.DataFrame,
    y: pd.Series,
    strategy: str,
    ratio: float,
) -> Tuple[pd.DataFrame, pd.Series, str]:
    if strategy == "none":
        return X.reset_index(drop=True), y.reset_index(drop=True), "none"

    sampling_strategy = build_sampling_strategy(y, ratio)
    if not sampling_strategy:
        return X.reset_index(drop=True), y.reset_index(drop=True), "skipped_ratio_already_met"

    minority_count = int((y == 0).sum())
    if minority_count < 2:
        return X.reset_index(drop=True), y.reset_index(drop=True), "fallback_too_few_minority"

    try:
        neighbors = max(1, min(5, minority_count - 1))
        if strategy == "smote":
            sampler = SMOTE(
                sampling_strategy=sampling_strategy,
                random_state=RANDOM_STATE,
                k_neighbors=neighbors,
            )
        elif strategy == "adasyn":
            sampler = ADASYN(
                sampling_strategy=sampling_strategy,
                random_state=RANDOM_STATE,
                n_neighbors=neighbors,
            )
        else:
            raise ValueError(f"Oversample strategy khong hop le: {strategy}")
        X_res, y_res = sampler.fit_resample(X, y)
        status = f"{strategy}_ok"
        return (
            pd.DataFrame(X_res, columns=X.columns).reset_index(drop=True),
            pd.Series(y_res, name=y.name).reset_index(drop=True),
            status,
        )
    except Exception as exc:
        print(f"  [WARN] {strategy} ratio={ratio} loi: {exc}. Fallback sang sample_weight.")
        return X.reset_index(drop=True), y.reset_index(drop=True), f"fallback_{strategy}_failed"


def make_sample_weight(y: pd.Series, non_positive_weight: float) -> np.ndarray:
    return np.where(np.asarray(y) == 0, float(non_positive_weight), 1.0)


def fit_xgb_binary(
    X_fit: pd.DataFrame,
    y_fit: pd.Series,
    X_eval: pd.DataFrame,
    y_eval: pd.Series,
    strategy: str,
    ratio: float,
    non_positive_weight: float,
    seed: int,
) -> Tuple[XGBClassifier, str, Counter]:
    X_res, y_res, oversample_status = apply_oversampling(X_fit, y_fit, strategy, ratio)
    sample_weight = make_sample_weight(y_res, non_positive_weight)
    params = make_xgb_params(seed)
    model = XGBClassifier(**params)
    model.fit(
        X_res,
        y_res,
        sample_weight=sample_weight,
        eval_set=[(X_eval, y_eval)],
        verbose=False,
    )
    return model, oversample_status, Counter(y_res)


def get_positive_proba(model: XGBClassifier, X: pd.DataFrame) -> np.ndarray:
    proba = np.asarray(model.predict_proba(X))
    if proba.ndim == 1:
        return proba
    if proba.shape[1] == 1:
        return proba[:, 0]
    return proba[:, 1]


def predict_non_positive_threshold(proba_positive: np.ndarray, threshold_non_positive: float) -> np.ndarray:
    proba_non_positive = 1.0 - np.asarray(proba_positive)
    return np.where(proba_non_positive >= threshold_non_positive, 0, 1)


def metric_row(
    y_true: pd.Series,
    y_pred: np.ndarray,
    threshold: Optional[float] = None,
    proba_positive: Optional[np.ndarray] = None,
) -> Dict[str, float]:
    cm = confusion_matrix(y_true, y_pred, labels=[0, 1])
    tn, fp, fn, tp = cm.ravel()
    row: Dict[str, float] = {
        "precision_non_positive": precision_score(y_true, y_pred, pos_label=0, zero_division=0),
        "recall_non_positive": recall_score(y_true, y_pred, pos_label=0, zero_division=0),
        "f1_non_positive": f1_score(y_true, y_pred, pos_label=0, zero_division=0),
        "macro_f1": f1_score(y_true, y_pred, average="macro", zero_division=0),
        "balanced_accuracy": balanced_accuracy_score(y_true, y_pred),
        "accuracy": accuracy_score(y_true, y_pred),
        "TN": int(tn),
        "FP": int(fp),
        "FN": int(fn),
        "TP": int(tp),
        "TP_non_positive": int(tn),
        "FN_non_positive": int(fp),
        "FP_non_positive": int(fn),
        "TN_non_positive": int(tp),
    }
    if threshold is not None:
        row["threshold"] = float(threshold)
    if proba_positive is not None and len(np.unique(y_true)) == 2:
        try:
            row["auc"] = roc_auc_score(y_true, proba_positive)
        except Exception:
            row["auc"] = np.nan
    return row


def search_binary_thresholds(
    y_true: pd.Series,
    proba_positive: np.ndarray,
    thresholds: np.ndarray = THRESHOLD_GRID,
) -> Tuple[pd.DataFrame, pd.Series, pd.Series]:
    rows = []
    for threshold in thresholds:
        y_pred = predict_non_positive_threshold(proba_positive, float(threshold))
        rows.append(metric_row(y_true, y_pred, float(threshold), proba_positive))
    threshold_df = pd.DataFrame(rows)
    sort_macro = threshold_df.sort_values(
        ["macro_f1", "balanced_accuracy", "recall_non_positive", "precision_non_positive"],
        ascending=[False, False, False, False],
    )
    sort_recall = threshold_df.sort_values(
        ["recall_non_positive", "macro_f1", "balanced_accuracy", "precision_non_positive"],
        ascending=[False, False, False, False],
    )
    return threshold_df, sort_macro.iloc[0], sort_recall.iloc[0]


def evaluate_config(
    X_fit: pd.DataFrame,
    y_fit: pd.Series,
    X_val: pd.DataFrame,
    y_val: pd.Series,
    strategy: str,
    ratio: float,
    non_positive_weight: float,
    seed: int,
) -> Dict[str, object]:
    model, oversample_status, resampled_counts = fit_xgb_binary(
        X_fit,
        y_fit,
        X_val,
        y_val,
        strategy,
        ratio,
        non_positive_weight,
        seed,
    )
    proba_val = get_positive_proba(model, X_val)
    _, best_macro, best_recall = search_binary_thresholds(y_val, proba_val)
    row = best_macro.to_dict()
    row.update(
        {
            "oversample_strategy": strategy,
            "oversample_ratio": ratio,
            "non_positive_weight": non_positive_weight,
            "best_threshold": float(best_macro["threshold"]),
            "best_recall_threshold": float(best_recall["threshold"]),
            "best_recall_value": float(best_recall["recall_non_positive"]),
            "oversample_status": oversample_status,
            "resampled_non_positive": int(resampled_counts.get(0, 0)),
            "resampled_positive": int(resampled_counts.get(1, 0)),
            "best_iteration": int(model.best_iteration or model.n_estimators),
        }
    )
    return row


