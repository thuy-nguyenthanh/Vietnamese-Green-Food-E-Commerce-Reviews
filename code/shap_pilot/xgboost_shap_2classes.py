def normalize_binary_shap(raw_shap) -> Tuple[np.ndarray, str]:
    if isinstance(raw_shap, list):
        if len(raw_shap) >= 2:
            return np.asarray(raw_shap[1]), "SHAP list output; using class 1 values for positive."
        return np.asarray(raw_shap[0]), "SHAP list output with one class; treated as class 1 positive."

    values = np.asarray(raw_shap)
    if values.ndim == 2:
        return values, (
            "SHAP 2D output for binary XGBoost: values are log-odds contribution "
            "for class 1 (positive). For class 0 (non_positive), signs are reversed."
        )
    if values.ndim == 3:
        if values.shape[2] == 2:
            return values[:, :, 1], "SHAP 3D output; selected class 1 positive slice."
        if values.shape[0] == 2:
            return values[1, :, :], "SHAP 3D output; selected class 1 positive slice."
    raise ValueError(f"Khong nhan dien duoc SHAP shape: {values.shape}")


def shap_importance(shap_values: np.ndarray, X_shap: pd.DataFrame, target_label: str) -> pd.DataFrame:
    rows = []
    for idx, feature in enumerate(X_shap.columns):
        feature_values = X_shap[feature].to_numpy(dtype=float)
        shap_feature = shap_values[:, idx]
        if np.std(feature_values) > 0 and np.std(shap_feature) > 0:
            corr = float(np.corrcoef(feature_values, shap_feature)[0, 1])
        else:
            corr = 0.0
        if corr > 0.05:
            direction = f"Higher feature value tends to increase {target_label}"
        elif corr < -0.05:
            direction = f"Higher feature value tends to decrease {target_label}"
        else:
            direction = f"No clear monotonic direction for {target_label}"
        rows.append(
            {
                "feature": feature,
                "mean_abs_shap": float(np.mean(np.abs(shap_feature))),
                "mean_shap": float(np.mean(shap_feature)),
                "std_shap": float(np.std(shap_feature)),
                "corr_feature_shap": corr,
                "direction_note": direction,
            }
        )
    return pd.DataFrame(rows).sort_values("mean_abs_shap", ascending=False).reset_index(drop=True)


def plot_shap_bar(importance_df: pd.DataFrame, file_name: str, title: str) -> None:
    data = importance_df.head(20).sort_values("mean_abs_shap", ascending=True)
    fig, ax = plt.subplots(figsize=(9, max(5, len(data) * 0.28)))
    ax.barh(data["feature"], data["mean_abs_shap"])
    ax.set_xlabel("Mean absolute SHAP value")
    ax.set_title(title)
    plt.tight_layout()
    savefig(file_name)


def run_shap_analysis(model: XGBClassifier, X_test: pd.DataFrame) -> Tuple[pd.DataFrame, pd.DataFrame, pd.DataFrame, str]:
    print_section("BUOC 7 - SHAP CHO BEST 2-CLASS MODEL")
    sample_n = min(SHAP_SAMPLE_SIZE, len(X_test))
    X_shap = X_test.sample(sample_n, random_state=RANDOM_STATE).copy()
    print(f"  SHAP sample size: {sample_n:,}")

    explainer = shap.TreeExplainer(model)
    raw_shap = explainer.shap_values(X_shap)
    shap_positive, shap_note = normalize_binary_shap(raw_shap)
    shap_non_positive = -shap_positive

    shap_positive_df = shap_importance(shap_positive, X_shap, "positive")
    shap_non_positive_df = shap_importance(shap_non_positive, X_shap, "non_positive")
    shap_overall_df = shap_positive_df[["feature", "mean_abs_shap"]].copy()
    shap_overall_df = shap_overall_df.sort_values("mean_abs_shap", ascending=False).reset_index(drop=True)

    save_csv(shap_overall_df, "shap_importance_overall.csv")
    save_csv(shap_non_positive_df, "shap_importance_non_positive.csv")
    save_csv(shap_positive_df, "shap_importance_positive.csv")

    plot_shap_bar(shap_overall_df, "shap_bar_overall.png", "SHAP overall importance - optimized binary model")
    plot_shap_bar(
        shap_non_positive_df,
        "shap_bar_non_positive.png",
        "SHAP importance for class non_positive",
    )

    try:
        plt.figure(figsize=(10, 7))
        shap.summary_plot(
            shap_non_positive,
            X_shap,
            feature_names=list(X_shap.columns),
            show=False,
            plot_size=None,
        )
        plt.title("SHAP beeswarm - class non_positive")
        plt.tight_layout()
        savefig("shap_beeswarm_non_positive.png")
    except Exception as exc:
        print(f"  [WARN] Khong ve duoc beeswarm non_positive: {exc}")

    print("  SHAP note:", shap_note)
    return shap_overall_df, shap_non_positive_df, shap_positive_df, shap_note


